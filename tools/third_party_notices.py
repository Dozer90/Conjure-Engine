#!/usr/bin/env python3
"""Builds and checks THIRD_PARTY_NOTICES.md, the tracked list of the third-party software Conjure uses.

Every dependency is registered next to its pin in third_party/CMakeLists.txt or a file it includes (jxl.cmake), with
conjure_third_party_notice (cmake/ConjureNotices.cmake). A configure writes what it registered into
<build>/notices/third_party_notices.json: each notice with its name, pin, licence and scope, whether that tree uses
it, and the licence files it found in the fetched sources. This tool turns one such manifest into
THIRD_PARTY_NOTICES.md at the repository root: a table of all notices and one section per notice with the licence
text copied from those files. Nothing in the document is typed by hand, and no licence text comes from anywhere but
the file the manifest names.

No single tree fetches everything (Direct3D 12 headers on Windows, Vulkan headers and glslang where the Vulkan
backend is built), so the document is merged:

  - a notice the tree uses gets its section written anew from the licence files;
  - a notice the tree knows but does not use keeps the section the document already has, byte for byte. It is an
    error when the document has none, or when its section was written for another name, pin, licence, scope,
    source or note than the tree registers (a notice registered without a pin, as for software the build machine
    provides instead of a download, .NET and the Visual C++ runtime, is not compared on its version): run the tool on
    a tree that fetches the software;
  - a section whose notice is no longer registered is dropped.

The licence text of software that is found on the build machine instead of pinned (.NET) is never part of the
document; the build writes it into THIRD_PARTY_NOTICES.txt next to conjure_runtime, and the section says so.

--check writes nothing and exits 1 when the document differs from what would be written; the CTest entry
notices.up_to_date runs it against the manifest of its own tree, so a changed pin, licence file or note fails on
every platform that fetches the dependency.

Usage:
    python tools/third_party_notices.py --build-dir build/<tree>             # write THIRD_PARTY_NOTICES.md
    python tools/third_party_notices.py --build-dir build/<tree> --check     # exit 1 when it would change
    python tools/third_party_notices.py --manifest <third_party_notices.json> [--output <file>] [--check]

A tree that fetches everything on Windows: python tools/build.py --build-dir build/<name> --configure-only --
-DCONJURE_RHI_VULKAN=ON (docs/handbook/getting-started.md 11).

Exit codes: 0 written or up to date, 1 out of date or not buildable from this manifest, 2 bad arguments.
"""

from __future__ import annotations

import argparse
import difflib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCUMENT_NAME = "THIRD_PARTY_NOTICES.md"
MANIFEST_LOCATION = pathlib.PurePosixPath("notices/third_party_notices.json")
MANIFEST_VERSION = 1

# Every section opens with this comment; the JSON after it is the notice the section was written for.
MARKER_PREFIX = "<!-- notice: "
MARKER_SUFFIX = " -->"
# The line after the last section.
POSTAMBLE_MARKER = "<!-- end of the notices -->"
METADATA_KEYS = ("id", "name", "version", "license", "scope", "url", "note", "hostProvided")
SCOPES = ("runtime", "editor", "build")
SCOPE_LABELS = {"runtime": "Runtime", "editor": "Editor", "build": "Build"}
MAX_DIFF_LINES = 60

PREAMBLE = """\
# Third-party notices

<!-- Generated by tools/third_party_notices.py from the licence files of the pinned dependencies. Do not edit:
     change the notice in third_party/CMakeLists.txt, or in the file it includes that registers it (jxl.cmake),
     and run the tool (docs/handbook/getting-started.md 11). -->

Conjure is licensed under the Apache License, Version 2.0 ([LICENSE](LICENSE), [NOTICE](NOTICE)). It is built from
the third-party software below, each under its own licence. Every section names the software, its pinned version,
where it comes from and its licence. The licence text follows as the pinned source publishes it; a section without
one says why.

Where the software ends up decides who has to pass its notice on:

- **Runtime**: linked into `conjure_shared` or `conjure_runtime`, or placed next to them. A build of
  `conjure_runtime` writes Conjure's own notice and the notices of what it links into `THIRD_PARTY_NOTICES.txt`
  next to the executable, and an export that copies the runtime copies that file into the game folder. What a
  build links depends on its platform and options (Direct3D 12 or Vulkan, physics, audio, scripting), so that file
  is the list for one build and this document is the list for all of them.
- **Editor**: linked into `conjure_shared` and `conjure_editor` in a build that has the editor (Debug and
  Development), and part of that build's `THIRD_PARTY_NOTICES.txt`. Never part of a Distribution build.
- **Build**: a build or test tool. In no binary that ships.

"""

POSTAMBLE = """\

Assets are not part of this list. The test assets a script downloads carry their licences in
`tools/test_assets.json`, and the art packs of the demo games, which the repository does not hold, are described
in `samples/assets/README.md`.
"""


class notices_error(Exception):
    """A manifest or document this tool cannot work with; the message is what the user reads."""


def normalise_licence_text(data: bytes, origin: str) -> str:
    """The text of a licence file as the document prints it: UTF-8, no byte order mark, LF line ends, no blank
    lines before the first line (whose indentation is kept) and no white space after the last one."""
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError as failure:
        raise notices_error(f"{origin}: not UTF-8 ({failure})") from failure
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    while lines and not lines[0].strip(" \t"):
        lines.pop(0)
    text = "\n".join(lines).rstrip(" \t\n")
    if not text:
        raise notices_error(f"{origin}: the licence file is empty")
    return text


def escape_markdown(text: str) -> str:
    """Text as Markdown shows it literally (a file pattern such as *.dll is not emphasis)."""
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", text)


def fence_for(text: str) -> str:
    """A code fence longer than every run of backticks in the text."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def metadata_of(notice: dict) -> dict:
    return {key: notice[key] for key in METADATA_KEYS}


def render_marker(metadata: dict) -> str:
    encoded = json.dumps(metadata, sort_keys=True, ensure_ascii=True)
    if "--" in encoded:
        raise notices_error(f"notice '{metadata['id']}': a text holds '--', which an HTML comment cannot carry")
    return f"{MARKER_PREFIX}{encoded}{MARKER_SUFFIX}"


def render_section(metadata: dict, texts: list[tuple[str, str]]) -> str:
    """One section: the marker, the heading, the facts and the licence texts (label, text)."""
    lines = [render_marker(metadata), f'<a id="notice-{metadata["id"]}"></a>', ""]
    lines.extend([f"## {escape_markdown(metadata['name'])}", ""])
    if metadata["hostProvided"]:
        lines.append("- Version: the one installed on the machine that builds the engine")
    elif metadata["version"]:
        lines.append(f"- Version: `{metadata['version']}`")
    lines.append(f"- Licence: {escape_markdown(metadata['license'])}")
    if metadata["url"]:
        lines.append(f"- Source: <{metadata['url']}>")
    lines.append(f"- Ends up in: {SCOPE_LABELS[metadata['scope']]}")
    lines.append("")
    if metadata["note"]:
        lines.extend([escape_markdown(metadata["note"]), ""])
    if metadata["hostProvided"]:
        lines.extend([
            "Its licence text is not part of this document, because the software is not pinned: a build writes the "
            "licence files of the installation it links into `THIRD_PARTY_NOTICES.txt` next to `conjure_runtime`.",
            "",
        ])
    elif not texts:
        lines.extend(["No licence text is reproduced here: the terms are published at the source above.", ""])
    for label, text in texts:
        fence = fence_for(text)
        lines.extend([f"`{label}`:", "", f"{fence}text", text, fence, ""])
    return "\n".join(lines)


def parse_sections(document: str) -> dict[str, tuple[dict, str]]:
    """The sections of a document by notice id: the notice each was written for and its text, marker included."""
    sections: dict[str, tuple[dict, str]] = {}
    current: list[str] | None = None
    metadata: dict = {}

    def close() -> None:
        if current is None:
            return
        while current and not current[-1]:
            current.pop()
        sections[metadata["id"]] = (metadata, "\n".join(current) + "\n")

    for line in document.split("\n"):
        if line.startswith(MARKER_PREFIX) and line.endswith(MARKER_SUFFIX):
            close()
            try:
                metadata = json.loads(line[len(MARKER_PREFIX):-len(MARKER_SUFFIX)])
            except json.JSONDecodeError as failure:
                raise notices_error(f"{DOCUMENT_NAME}: a section marker is not JSON ({failure})") from failure
            if not isinstance(metadata, dict) or any(key not in metadata for key in METADATA_KEYS):
                raise notices_error(f"{DOCUMENT_NAME}: a section marker lacks one of {', '.join(METADATA_KEYS)}")
            if metadata["id"] in sections:
                raise notices_error(f"{DOCUMENT_NAME}: two sections for '{metadata['id']}'")
            current = [line]
        elif line == POSTAMBLE_MARKER:
            close()
            current = None
        elif current is not None:
            current.append(line)
    close()
    return sections


def load_manifest(path: pathlib.Path) -> dict:
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except OSError as failure:
        raise notices_error(f"{path}: cannot be read ({failure.strerror}); configure the build tree first") from failure
    except (UnicodeDecodeError, json.JSONDecodeError) as failure:
        raise notices_error(f"{path}: not a notices manifest ({failure})") from failure
    if not isinstance(manifest, dict) or manifest.get("version") != MANIFEST_VERSION:
        raise notices_error(f"{path}: not a notices manifest of version {MANIFEST_VERSION}")
    notices = manifest.get("notices")
    if not isinstance(notices, list):
        raise notices_error(f"{path}: 'notices' is not a list")
    seen: set[str] = set()
    for notice in notices:
        required = METADATA_KEYS + ("used", "files")
        if not isinstance(notice, dict) or any(key not in notice for key in required):
            raise notices_error(f"{path}: a notice lacks one of {', '.join(required)}")
        if notice["scope"] not in SCOPES:
            raise notices_error(f"{path}: notice '{notice['id']}' has the unknown scope '{notice['scope']}'")
        if notice["id"] in seen:
            raise notices_error(f"{path}: notice '{notice['id']}' is listed twice")
        seen.add(notice["id"])
    return manifest


def same_notice(tracked: dict, registered: dict) -> bool:
    """True when a tracked section was written for the notice a tree registers. A notice registered without a
    version (software that is not pinned: what the build machine provides, such as .NET and the Visual C++ runtime,
    or code kept in the tree) matches a tracked section of any version."""
    for key in METADATA_KEYS:
        if key == "version" and not registered["version"]:
            continue
        if tracked[key] != registered[key]:
            return False
    return True


def build_document(manifest: dict, tracked: str) -> tuple[str, list[str]]:
    """The document this manifest and the tracked document merge into, and what prevents the merge."""
    problems: list[str] = []
    tracked_sections = parse_sections(tracked)
    rows: list[str] = []
    sections: list[str] = []
    for notice in manifest["notices"]:
        metadata = metadata_of(notice)
        name = metadata["name"]
        if notice["used"]:
            texts: list[tuple[str, str]] = []
            for entry in ([] if metadata["hostProvided"] else notice["files"]):
                path = pathlib.Path(entry["path"])
                try:
                    data = path.read_bytes()
                except OSError as failure:
                    problems.append(f"{name}: the licence file '{path}' cannot be read ({failure.strerror}); "
                                    "configure the build tree again")
                    continue
                texts.append((entry["label"], normalise_licence_text(data, str(path))))
            section = render_section(metadata, texts)
        else:
            kept = tracked_sections.get(metadata["id"])
            if kept is None:
                problems.append(f"{name}: this tree does not use it and {DOCUMENT_NAME} has no section for it; "
                                "run the tool on a tree that fetches it")
                continue
            if not same_notice(kept[0], metadata):
                problems.append(f"{name}: this tree does not use it, and the section of {DOCUMENT_NAME} was written "
                                "for another pin, licence or note than the tree registers; run the tool on a tree "
                                "that fetches it")
                continue
            metadata, section = kept
        version = f"`{metadata['version']}`" if metadata["version"] else ""
        if metadata["hostProvided"]:
            version = "installed"
        rows.append(f"| [{escape_markdown(metadata['name'])}](#notice-{metadata['id']}) | {version} "
                    f"| {escape_markdown(metadata['license'])} | {SCOPE_LABELS[metadata['scope']]} |")
        sections.append(section)
    table = ["| Software | Version | Licence | Ends up in |", "|---|---|---|---|", *rows]
    document = PREAMBLE + "\n".join(table) + "\n\n" + "\n".join(sections) + "\n" + POSTAMBLE_MARKER + "\n" + POSTAMBLE
    return document, problems


def dropped_sections(manifest: dict, tracked: str) -> list[str]:
    """The names of the tracked sections whose notice the manifest no longer registers."""
    registered = {notice["id"] for notice in manifest["notices"]}
    tracked_sections = parse_sections(tracked)
    return [metadata["name"] for identifier, (metadata, _) in tracked_sections.items() if identifier not in registered]


def run(manifest_path: pathlib.Path, output: pathlib.Path, check: bool) -> int:
    manifest = load_manifest(manifest_path)
    try:
        tracked = output.read_text(encoding="utf-8")
    except FileNotFoundError:
        tracked = ""
    except (OSError, UnicodeDecodeError) as failure:
        raise notices_error(f"{output}: cannot be read ({failure})") from failure
    tracked = tracked.replace("\r\n", "\n")
    document, problems = build_document(manifest, tracked)
    if problems:
        for problem in problems:
            print(f"third_party_notices: {problem}", file=sys.stderr)
        return 1
    if document == tracked:
        print(f"third_party_notices: {output.name} is up to date ({len(manifest['notices'])} notices)")
        return 0
    if check:
        difference = list(difflib.unified_diff(tracked.split("\n"), document.split("\n"), output.name, "generated",
                                               lineterm="", n=1))
        for line in difference[:MAX_DIFF_LINES]:
            print(line, file=sys.stderr)
        if len(difference) > MAX_DIFF_LINES:
            print(f"... {len(difference) - MAX_DIFF_LINES} more line(s)", file=sys.stderr)
        print(f"third_party_notices: {output.name} is out of date; run: python tools/third_party_notices.py "
              f"--manifest \"{manifest_path}\"", file=sys.stderr)
        return 1
    for name in dropped_sections(manifest, tracked):
        print(f"third_party_notices: dropped the section of {name}, which is no longer registered")
    with open(output, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(document)
    print(f"third_party_notices: wrote {output} ({len(manifest['notices'])} notices)")
    return 0


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Builds and checks THIRD_PARTY_NOTICES.md from a build tree's "
                                                 "notices manifest.")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--build-dir", type=pathlib.Path,
                        help="a configured build tree; its manifest is <dir>/notices/third_party_notices.json")
    source.add_argument("--manifest", type=pathlib.Path, help="the manifest file itself")
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / DOCUMENT_NAME,
                        help="the document to write or check (default: THIRD_PARTY_NOTICES.md of the repository)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 when the document differs from what would be written")
    options = parser.parse_args(arguments)
    manifest_path = options.manifest if options.manifest is not None else options.build_dir / MANIFEST_LOCATION
    try:
        return run(manifest_path, options.output, options.check)
    except notices_error as failure:
        print(f"third_party_notices: {failure}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
